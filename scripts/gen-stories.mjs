#!/usr/bin/env node
/**
 * Generates one exhaustive Storybook file per component from `packages/davinci-ai/dist/components.json`
 * (run `pnpm build` first) plus the hand-written usage in `scripts/stories.spec.mjs`.
 *
 * Every component gets: Default (with Controls), one story that renders every value of every enum prop,
 * a Matrix of the two main variant axes, a States story (disabled / invalid / selected …) and any extras from the spec.
 * Hand-written extras and usage live in the spec; never edit the generated `*.stories.tsx` files.
 *
 *   node scripts/gen-stories.mjs [Name ...]     # all components, or only the named ones
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SPEC, PLAY } from './stories.spec.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'packages/davinci-ai/dist/components.json'), 'utf8'));
const all = manifest.components ?? manifest;
const only = process.argv.slice(2);
const FIXTURE_TYPES = [...readFileSync(resolve(root, 'packages/davinci-ai/src/stories/fixtures.tsx'), 'utf8').matchAll(/export interface (\w+)/g)].map((m) => m[1]);
const FIXTURES = [...readFileSync(resolve(root, 'packages/davinci-ai/src/stories/fixtures.tsx'), 'utf8').matchAll(/export (?:const|interface) (\w+)/g)].map((m) => m[1]).concat(['series', 'seriesDown']);

/** Enum props that are plumbing, not visual variants. */
const SKIP_ENUM = new Set(['type', 'validationBehavior', 'as', 'titleLevel', 'level', 'placement', 'keyboardActivation', 'selectionMode', 'defaultValue', 'value', 'position', 'defaultSide']);
/** Boolean props worth showing as a state. */
const STATE_BOOLS = ['isDisabled', 'isInvalid', 'isReadOnly', 'isRequired', 'isOptional', 'isSelected', 'defaultSelected', 'isIndeterminate', 'isLoading', 'isIndeterminate', 'isStreaming', 'fullWidth', 'dense', 'collapsed', 'defaultCollapsed', 'zebra', 'stickyHeader', 'decorative', 'dot', 'circle', 'markers', 'baseline', 'showValue', 'hideIcon', 'hideSteppers', 'hideOutput', 'external', 'attached', 'wrap', 'flush', 'padded', 'spotlight', 'fill', 'showLegend', 'dismissible', 'allowsMultipleExpanded', 'defaultExpanded', 'isExpanded', 'multiple', 'floating', 'docked', 'countUp', 'allowCustom', 'dotGrid', 'canvas', 'colorBlindSafe', 'isIndeterminate'];
const ENUM_ORDER = ['variant', 'intent', 'size', 'orientation', 'layout', 'status', 'side', 'density'];

const q = (s) => JSON.stringify(s);
const titleCase = (s) => s.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()).trim();

function gen(name) {
  const c = all[name];
  const sp = SPEC[name];
  if (!c) throw new Error(`Unknown component ${name}`);
  if (!sp) throw new Error(`No story spec for ${name} – add it to scripts/stories.spec.mjs`);
  const props = c.props ?? {};
  const enums = Object.entries(props)
    .filter(([k, v]) => v.type === 'enum' && v.values?.length && !SKIP_ENUM.has(k) && !(sp.skip ?? []).includes(k))
    .sort(([a], [b]) => (ENUM_ORDER.indexOf(a) + 100) % 100 - (ENUM_ORDER.indexOf(b) + 100) % 100);
  const bools = [...new Set(STATE_BOOLS)].filter((k) => props[k] && props[k].type === 'boolean' && !(sp.skip ?? []).includes(k));
  const text = [sp.r, sp.pre ?? '', ...(sp.x ?? []).map((e) => e[1]), ...(PLAY[name] ?? []).map((e) => e[2] ?? '')].join('\n');
  const used = Object.keys(all).filter((n) => new RegExp(`<${n}\\b`).test(text) || new RegExp(`\\b${n}\\b(?=\\s*=\\s*|\\()`).test(''));
  const lib = [...new Set([name, ...(sp.imp ?? []), ...used, ...(/\buseToast\b/.test(text) ? ['useToast'] : []), ...(/<Tag\b/.test(text) ? ['Tag'] : [])])];
  const fxUsed = FIXTURES.filter((n) => new RegExp(`\\b${n}\\b`).test(text));
  const fxAll = [...new Set([...(sp.fx ?? []), ...fxUsed])];
  const dir = resolve(root, dirname(c.source));
  const rel = c.category === 'Foundations' ? '../stories' : '../../stories';
  const catTitle = c.category;

  const argTypes = {};
  for (const [k, v] of Object.entries(props)) {
    if (v.type === 'enum' && v.values) argTypes[k] = { control: v.values.length <= 4 ? 'inline-radio' : 'select', options: v.values.map((x) => (/^\d+$/.test(x) ? Number(x) : x)) };
  }
  const desc = [c.description, c.whenToUse && `**Use:** ${c.whenToUse}`, c.whenNotToUse && `**Don't:** ${c.whenNotToUse}`].filter(Boolean).join('\n\n');

  const out = [];
  out.push('/* eslint-disable @typescript-eslint/no-explicit-any */');
  out.push('// GENERATED by scripts/gen-stories.mjs from components.json + scripts/stories.spec.mjs – edit the spec, not this file.');
  out.push(`import type { Meta, StoryObj } from '@storybook/react-vite';`);
  const playText = JSON.stringify(PLAY[name] ?? []);
  const testImports = ['expect', 'userEvent', 'within'].filter((n) => new RegExp(`\\b${n}\\b`).test(playText));
  if (testImports.length) out.push(`import { ${testImports.join(', ')} } from 'storybook/test';`);
  out.push(`import { ${lib.join(', ')} } from '@davinci-ai/react';`);
  const helperImport = out.length;
  if (fxAll.length) out.push(`import { ${fxAll.map((n) => (FIXTURE_TYPES.includes(n) ? `type ${n}` : n)).join(', ')} } from '${rel}/fixtures';`);
  if (sp.ext) out.push(sp.ext);
  out.push('');
  if (sp.pre) out.push(sp.pre, '');
  out.push(`const render = (P: any) => (${sp.r.replace(/\{\.\.\.P\}/g, '{...P}')});`);
  out.push(`const frame = (n: React.ReactElement) => ${sp.w ? `<div style={{ width: ${typeof sp.w === 'number' ? sp.w : q(sp.w)}${sp.h ? `, height: ${sp.h}` : ''} }}>{n}</div>` : '<>{n}</>'};`);
  out.push('');
  out.push(`const meta: Meta = {`);
  out.push(`  title: ${q(`Components/${catTitle}/${name}`.replace('Components/Foundations/', 'Foundations/'))},`);
  out.push(`  component: ${name} as any,`);
  out.push(`  args: ${sp.a ?? '{}'},`);
  out.push(`  argTypes: ${JSON.stringify(argTypes)},`);
  out.push(`  parameters: { ${sp.layout ? `layout: ${q(sp.layout)}, ` : ''}docs: { description: { component: ${q(desc)} } } },`);
  out.push(`};`);
  out.push('export default meta;');
  out.push('type S = StoryObj<typeof meta>;');
  out.push('');
  out.push(`export const Default: S = { render: (args) => frame(render(args)) };`);

  const base = `(meta.args ?? {})`;
  const cell = (extra) => `frame(render({ ...${base}, ${extra} }))`;

  if (!sp.nv && enums.length) {
    out.push('');
    out.push('/** Every value of every variant prop, one section per prop. */');
    out.push(`export const Variants: S = {`);
    out.push(`  render: () => (`);
    out.push(`    <Col gap={24}>`);
    for (const [k, v] of enums) {
      const vals = v.values.map((x) => (/^\d+$/.test(x) ? Number(x) : x));
      out.push(`      <Section title=${q(k)}>`);
      out.push(`        ${sp.col ? '<Col>' : '<Row gap={16} align="start">'}`);
      for (const val of vals) out.push(`          <div key=${q(String(val))} style={{ ${sp.col ? '' : 'display: \'grid\', gap: 6, justifyItems: \'start\''} }}><small style={{ color: 'var(--dv-text-muted)', fontSize: 11 }}>${String(val)}</small>{${cell(`${q(k)}: ${typeof val === 'number' ? val : q(val)}`)}}</div>`.replace('style={{  }}', ''));
      out.push(`        ${sp.col ? '</Col>' : '</Row>'}`);
      out.push(`      </Section>`);
    }
    out.push(`    </Col>`);
    out.push(`  ),`);
    out.push(`};`);
  }

  if (!sp.nv && enums.length >= 2) {
    const [[k1, v1], [k2, v2]] = enums;
    const a = v1.values.map((x) => (/^\d+$/.test(x) ? Number(x) : x));
    const b = v2.values.map((x) => (/^\d+$/.test(x) ? Number(x) : x));
    out.push('');
    out.push(`/** ${k1} × ${k2}. */`);
    out.push(`export const Matrix: S = {`);
    out.push(`  render: () => (`);
    out.push(`    <div style={{ display: 'grid', gap: 16 }}>`);
    out.push(`      {${JSON.stringify(a)}.map((r) => (`);
    out.push(`        <Section key={String(r)} title={${q(k1 + ' = ')} + String(r)}>`);
    out.push(`          <Row gap={12}>{${JSON.stringify(b)}.map((c) => <div key={String(c)}>{${cell(`${q(k1)}: r, ${q(k2)}: c`)}}</div>)}</Row>`);
    out.push(`        </Section>`);
    out.push(`      ))}`);
    out.push(`    </div>`);
    out.push(`  ),`);
    out.push(`};`);
  }

  const states = [...(sp.st ?? [])];
  if (!sp.nst) for (const k of bools) states.push([k, `{ ${k}: true, ...(${sp.sa ?? '{}'}) }`]);
  const seen = new Set();
  const uniq = states.filter(([l]) => !seen.has(l) && seen.add(l));
  if (uniq.length) {
    out.push('');
    out.push('/** Boolean and state props switched on, one at a time. */');
    out.push(`export const States: S = {`);
    out.push(`  render: () => (`);
    out.push(`    <Col gap={20}>`);
    out.push(`      <Section title="default">{frame(render({ ...${base} }))}</Section>`);
    for (const [l, p] of uniq) out.push(`      <Section title=${q(l)}>{frame(render({ ...${base}, ...${p} }))}</Section>`);
    out.push(`    </Col>`);
    out.push(`  ),`);
    out.push(`};`);
  }

  for (const [n, jsx, doc] of sp.x ?? []) {
    out.push('');
    if (doc) out.push(`/** ${doc} */`);
    const id0 = n.replace(/[^A-Za-z0-9]/g, '');
    const id = [...lib, ...fxAll, 'Col', 'Row', 'Section', 'Default', 'Variants', 'Matrix', 'States'].includes(id0) ? `${id0}Story` : id0;
    out.push(`export const ${id}: S = { name: ${q(n)}, render: () => (${jsx}) };`);
  }
  out.push('');

  for (const [n, play, extra] of PLAY[name] ?? []) {
    out.push('');
    out.push(`export const ${n}: S = { ${extra ? `${extra}, ` : ''}${/(^|, )render:/.test(extra ?? '') ? '' : 'render: (a) => frame(render(a)), '}${play ? `play: async (${/canvasElement/.test(play) ? '{ canvasElement }' : ''}) => { ${play} }` : ''} };`);
  }
  const body = out.slice(helperImport).join('\n');
  const helpers = ['Col', 'Row', 'Section'].filter((h) => new RegExp(`<${h}\\b`).test(body));
  if (helpers.length) out.splice(helperImport, 0, `import { ${helpers.join(', ')} } from '${rel}/helpers';`);
  mkdirSync(dir, { recursive: true });
  const file = resolve(dir, `${name}.stories.tsx`);
  writeFileSync(file, out.join('\n'));
  return file;
}

const names = only.length ? only : Object.keys(all);
const done = [];
const missing = [];
for (const n of names) {
  try { done.push(gen(n)); } catch (e) { if (/No story spec/.test(e.message)) missing.push(n); else throw e; }
}
console.log(`generated ${done.length} story files`);
if (missing.length) { console.error(`missing specs (${missing.length}): ${missing.join(', ')}`); process.exitCode = 1; }
void titleCase;
